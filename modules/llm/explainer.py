# this file defines the LLM explanation layer,
# which is responsible for generating recruiter-friendly explanations for
# the computed resume-job match scores. The LLM does not calculate or modify the scores;
# it only explains why a particular score was assigned based on the job description and
# extracted candidate fields. The explanation is returned in a structured JSON format.

"""
LLM explanation layer.

task:
- Explain the already computed resume-job match score.
- Never calculate or modify the score.
- Return a structured JSON explanation.

The LLM only explains WHY the score was assigned.
Scoring is performed elsewhere by the deterministic pipeline.
"""

import json
from typing import Any

from modules.llm.client import client, MODEL_NAME
from modules.llm.prompts import EXPLANATION_SYSTEM_PROMPT


def generate_explanation(
    jd_text: str,
    extracted_fields: dict[str, Any],
    final_score: float,
) -> dict[str, Any]:
    """
    Generate a recruiter-friendly explanation for the computed resume score.

    Args:
        jd_text: Job description.
        extracted_fields: Structured candidate information.
        final_score: Score computed by the scoring pipeline.

    Returns:
        JSON explanation generated by the LLM.
    """

    user_content = f"""
Job Description:
{jd_text}

Candidate Extracted Fields:
{json.dumps(extracted_fields, indent=2)}

Final Computed Match Score:
{final_score}/100
"""

    response = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {
                "role": "system",
                "content": EXPLANATION_SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": user_content,
            },
        ],
        temperature=0.3,
        response_format={"type": "json_object"},
    )

    raw = response.choices[0].message.content

    if raw is None:
        raise ValueError("LLM returned an empty response.")

    raw = raw.strip()

    # Remove markdown code fences if present.
    if raw.startswith("```"):
        raw = raw.removeprefix("```json")
        raw = raw.removeprefix("```")
        raw = raw.removesuffix("```")
        raw = raw.strip()

    try:
        explanation = json.loads(raw)

    except json.JSONDecodeError as e:
        raise ValueError(
            f"LLM returned invalid JSON.\n\nError: {e}\n\nOutput:\n{raw}"
        )

    return explanation
